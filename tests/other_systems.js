// Tiny homebrew ROMs for the other systems Mesen 2 runs (no BIOS needed), used by tests/core_test.js
// and tests/e2e_test.js. Each is a few bytes of code written for these tests: start, then loop.
// The NES one reads the controller every frame and paints the backdrop red while any button is
// held, black otherwise. The Game Boy one is an original Game Boy game with Super Game Boy features
// (as Super Mario Land 2): on the Game Boy its screen is grey (it has no Nintendo logo, so the boot
// screen stays up), on the Color it would get colours.
'use strict';

function nes() {
  const prg = new Uint8Array(0x4000).fill(0xEA);  // NOPs
  const code = [
    0x78, 0xD8, 0xA2, 0x40, 0x8E, 0x17, 0x40, 0xA2, 0xFF, 0x9A, 0xE8, 0x8E, 0x00, 0x20, 0x8E, 0x01, 0x20,  // init, PPU off
    0x2C, 0x02, 0x20, 0x10, 0xFB, 0x2C, 0x02, 0x20, 0x10, 0xFB,                                          // two vblanks
    // main: strobe the controller, read 8 buttons into $00
    0xA9, 0x01, 0x8D, 0x16, 0x40, 0xA9, 0x00, 0x8D, 0x16, 0x40, 0xA2, 0x08,
    0xAD, 0x16, 0x40, 0x4A, 0x26, 0x00, 0xCA, 0xD0, 0xF7,
    0x2C, 0x02, 0x20, 0x10, 0xFB,                                                                          // wait for vblank
    0xA9, 0x3F, 0x8D, 0x06, 0x20, 0xA9, 0x00, 0x8D, 0x06, 0x20,                                            // PPU address $3F00
    0xA5, 0x00, 0xF0, 0x04, 0xA9, 0x16, 0xD0, 0x02, 0xA9, 0x0F, 0x8D, 0x07, 0x20,                          // red or black
    0xA9, 0x00, 0x8D, 0x06, 0x20, 0x8D, 0x06, 0x20, 0x8D, 0x05, 0x20, 0x8D, 0x05, 0x20,                    // scroll 0
    0xA9, 0x0A, 0x8D, 0x01, 0x20,                                                                          // background on
    0x4C, 0x1B, 0xC0,                                                                                      // jmp main ($C01B)
  ];
  prg.set(code, 0);
  prg.set([0x00, 0xC0, 0x00, 0xC0, 0x00, 0xC0], 0x3FFA);  // NMI, RESET, IRQ -> $C000
  const rom = new Uint8Array(16 + 0x4000 + 0x2000);
  rom.set([0x4E, 0x45, 0x53, 0x1A, 1, 1, 0, 0], 0);
  rom.set(prg, 16);
  return rom;
}

function gb() {
  const rom = new Uint8Array(0x8000);
  rom.set([0x00, 0xC3, 0x50, 0x01], 0x100);          // nop; jp $0150
  rom.set([...Buffer.from('SWANTEST')], 0x134);
  rom[0x146] = 0x03; rom[0x14B] = 0x33;               // Super Game Boy features, as many original games
  // di; BGP = all colour 1; LCD and background on; jr $ (on the Game Boy: light grey)
  rom.set([0xF3, 0x3E, 0x55, 0xE0, 0x47, 0x3E, 0x91, 0xE0, 0x40, 0x18, 0xFE], 0x150);
  let c = 0;
  for (let i = 0x134; i <= 0x14C; i++) c = (c - rom[i] - 1) & 0xFF;
  rom[0x14D] = c;
  return rom;
}

function sms() {
  const rom = new Uint8Array(0x8000);
  rom.set([0xF3, 0x31, 0xF0, 0xDF, 0x18, 0xFE], 0);  // di; ld sp,$DFF0; jr $
  return rom;
}

function pce() {
  const rom = new Uint8Array(0x8000);
  rom.set([0x78, 0xD8, 0x80, 0xFE], 0);              // sei; cld; bra $ (bank 0 at $E000)
  rom.set([0x00, 0xE0, 0x00, 0xE0, 0x00, 0xE0, 0x00, 0xE0, 0x00, 0xE0], 0x1FF6);
  return rom;
}

function snes() {
  const rom = new Uint8Array(0x8000);
  rom.set([0x78, 0x18, 0xFB, 0x80, 0xFE], 0);        // sei; clc; xce; bra $ (at $8000)
  rom.set([...Buffer.from('SWAN TEST            ')], 0x7FC0);
  rom[0x7FD5] = 0x20; rom[0x7FD6] = 0x00; rom[0x7FD7] = 0x08; rom[0x7FD9] = 0x01;
  rom.set([0x00, 0x80, 0x00, 0x80], 0x7FEA);        // native NMI / reset
  rom.set([0x00, 0x80, 0x00, 0x80], 0x7FFA);        // emulation NMI, RESET -> $8000
  rom.set([0x00, 0x80], 0x7FFE);
  let sum = 0;
  rom[0x7FDC] = 0xFF; rom[0x7FDD] = 0xFF; rom[0x7FDE] = 0; rom[0x7FDF] = 0;
  for (const b of rom) sum = (sum + b) & 0xFFFF;
  rom[0x7FDE] = sum & 0xFF; rom[0x7FDF] = sum >> 8; rom[0x7FDC] = ~sum & 0xFF; rom[0x7FDD] = (~sum >> 8) & 0xFF;
  return rom;
}

module.exports = { nes, gb, sms, pce, snes };
